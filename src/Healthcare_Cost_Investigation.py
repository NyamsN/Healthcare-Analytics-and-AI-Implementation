# **Primary research question.** How do recorded total claim costs differ across encounter classes, and how far are
# those differences associated with procedure activity, encounter duration and payer?
#
# **Why it matters.** Encounter class (ambulatory, outpatient, wellness, urgent care, emergency, inpatient) is the most
# basic way a hospital plans capacity and budgets. If cost differences between classes are really driven by procedure
# activity or by who pays, then budgeting by class alone would mislead finance and operations managers.
#
# **Intended user.** The hospital's operations and finance analytics team (revenue-cycle and service-line managers).
#
# **Decision supported.** Which cost drivers to monitor and report alongside encounter class, and where payer coverage
# gaps should be investigated.
#
# **Evidence limits (summary).** The data is synthetic (generated by the Synthea simulator for one hospital), covers
# 974 patients, has no medication or line-item detail, and many patients appear many times. Findings describe
# associations in this dataset, not causes, and are not clinical evidence. Full discussion in Section 8.
#
