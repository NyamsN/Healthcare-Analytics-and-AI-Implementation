# %% [markdown]
# **What these checks mean.**
# * **Duration is not a reliable length-of-stay measure.** Most encounters have a fixed 15-minute duration, and 22,328
#   procedures start *after* their encounter's STOP time (median 1.4 h later, up to 182 days). STOP therefore marks
#   the end of the encounter record, not the end of care. Duration is still analysed (H3) but with this caveat.
# * **TOTAL_CLAIM_COST is not BASE + procedures.** The dictionary says the total includes medications, immunisations
#   and other line items that are not supplied, so only about 30% of encounters reconcile exactly. Some encounters have
#   procedure lines costing more than the claim total, so procedure costs and claim totals were apparently generated
#   independently: 5,086 encounters (18%) have procedure lines that cost more than the whole claim. We analyse
#   TOTAL_CLAIM_COST as recorded and do not "fix" it.
# * **BASE_ENCOUNTER_COST takes only five distinct values** (a fixed tariff per encounter type), so it carries almost
#   no information; TOTAL_CLAIM_COST is the meaningful outcome.
# * **Encounters after death and zero-cost encounters** are kept: they are few and removing them would require a
#   rule we cannot verify. They are flagged in the processed file.
# * **Missing REASONCODE (70% of encounters)** is structural: the dictionary says it is filled "only if this encounter
#   targeted a specific condition". It is not imputed. Missing DEATHDATE means the patient was alive at extract.

