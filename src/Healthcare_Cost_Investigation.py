# **Interpretation.** The χ² test rejects independence, but the effect is **small** (Cramér's V = 0.117). Adding payer
# to the model raises explained variation from a pseudo-R² of 0.04 to 0.81, confirming that **who pays, not what type
# of encounter it is, determines whether coverage is recorded**. A class effect remains after adjustment (Wald
# χ² = 37.7, p < 0.001), but its direction changes: emergency encounters look *less* likely to have zero coverage
