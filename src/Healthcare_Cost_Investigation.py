# **Interpretation.** Duration and cost are positively associated in all four testable classes (ρ = 0.17 to 0.48), so
# H0 is rejected. But once the number of procedures is held constant the picture splits: in ambulatory (partial
# ρ = 0.26) and outpatient (0.42) care the association remains, while in emergency (−0.09) and inpatient (−0.05, not
# significant) care it disappears. Longer emergency and inpatient encounters cost more only because they contain more
# procedures. **Practical significance:** duration is a weak and unreliable cost
# signal in this data; procedure counts are more informative. **Limitation:** encounter STOP times do not mark the end
# of care (Section 3.3), and 69% of durations are a default 15 minutes, so this result should not be used to estimate
# a cost per hour.
#
# ### H4. The share of encounters with zero payer coverage differs by encounter class
# * **H0:** zero coverage is independent of encounter class.
# * **H1:** the zero-coverage rate differs between classes.
# * **Variables:** zero_coverage (binary) × class (6 groups); then controlling for payer.
# * **Method:** χ² test of independence with Cramér's V; then a logistic regression of zero_coverage on class with payer
#   fixed effects and patient-clustered standard errors, to see whether any class difference survives once payer is
#   held constant. Uninsured encounters (always zero) are excluded from the adjusted model because they have no variation.
# * **Assumptions:** χ²: independent observations (violated by repeat patients; addressed by clustering in the logit),
#   expected counts ≥5 in every cell (checked).

# %%
ct = pd.crosstab(analysis["class"], analysis.zero_coverage)
chi2, pchi, dof, expct = stats.chi2_contingency(ct)
cv = np.sqrt(chi2 / (ct.values.sum() * (min(ct.shape) - 1)))
print(f"Min expected count = {expct.min():.0f}")
