#
# ## 6. Hypotheses and statistical tests
# **Method choice.** Costs are heavily skewed with unequal variances (Levene's test below), and groups are very unequal
# in size (1,135 inpatient vs 12,537 ambulatory). Mean-based tests (ANOVA, t-tests) would be dominated by a few extreme
# values, so the primary tests are rank-based (Kruskal–Wallis, Mann–Whitney, Spearman), with effect sizes reported
# alongside p-values because with n ≈ 28,000 even trivial differences are "significant". Encounter-level tests assume
# independence, which repeated patients violate, so every test is repeated on patient-level data in Section 7.

# %%
results = []

def eps_sq(H, n, k):
    return (H - k + 1) / (n - k)

groups = [analysis.loc[analysis["class"] == c, "TOTAL_CLAIM_COST"].values for c in CLASS_ORDER]
lev = stats.levene(*groups, center="median")
print(f"Brown–Forsythe (median-centred Levene) test of equal variances: W = {lev.statistic:.1f}, p = {lev.pvalue:.2e}")
print("Skewness by class:", {CLASS_LABEL[c]: round(stats.skew(g), 1) for c, g in zip(CLASS_ORDER, groups)})

# %% [markdown]
# ### H1. Total claim cost differs across encounter classes
# * **H0:** the distribution of TOTAL_CLAIM_COST is the same in all six encounter classes.
# * **H1:** at least one class has a stochastically higher or lower cost distribution.
# * **Variables:** TOTAL_CLAIM_COST (continuous, skewed) by ENCOUNTERCLASS (6 groups).
# * **Method:** Kruskal–Wallis H test, effect size ε²; Dunn post hoc comparisons with Holm correction.
# * **Assumptions:** independent observations (violated by repeat patients, checked in Section 7); ordinal or
#   continuous outcome (met); similar distribution shapes if interpreting as a median difference (not met, so the
#   result is read as a difference in distributions / mean ranks, with medians reported descriptively).

# %%
H, p = stats.kruskal(*groups)
e2 = eps_sq(H, len(analysis), len(CLASS_ORDER))
dunn = sp.posthoc_dunn(analysis.assign(c=analysis["class"].astype(str)), val_col="TOTAL_CLAIM_COST", group_col="c", p_adjust="holm")
dunn = dunn.loc[CLASS_ORDER, CLASS_ORDER]
dunn_long = [(CLASS_LABEL[a], CLASS_LABEL[b], dunn.loc[a, b]) for i, a in enumerate(CLASS_ORDER) for b in CLASS_ORDER[i + 1:]]
dunn_df = pd.DataFrame(dunn_long, columns=["class_a", "class_b", "p_holm"])
dunn_df["median_a"] = dunn_df.class_a.map({CLASS_LABEL[c]: desc.loc[c, "median"] for c in CLASS_ORDER})
dunn_df["median_b"] = dunn_df.class_b.map({CLASS_LABEL[c]: desc.loc[c, "median"] for c in CLASS_ORDER})
dunn_df["significant_0.05"] = dunn_df.p_holm < .05
save_tab(dunn_df.round(6), "T18_H1_dunn_posthoc")
results.append({"hypothesis": "H1 Cost differs across encounter classes", "test": "Kruskal–Wallis (6 groups)",
                "n": len(analysis), "statistic": f"H = {H:,.0f}", "p_value": p, "effect_size": f"ε² = {e2:.3f}",
                "decision": "Reject H0" if p < .05 else "Fail to reject H0"})
print(f"H = {H:,.1f}, df = 5, p = {p:.2e}, epsilon² = {e2:.3f}")
print(f"Non-significant pairs after Holm correction: {(~dunn_df['significant_0.05']).sum()} of {len(dunn_df)}")
dunn_df[~dunn_df["significant_0.05"]]

# %% [markdown]
# **Interpretation.** Encounter class is associated with claim cost (p far below 0.001) with a **medium** effect
# (ε² = 0.072 at encounter level, 0.150 at patient level; benchmarks 0.01 small, 0.08 medium, 0.26 large). Class alone
# accounts for only about 7–15% of the variation in cost ranks, so most cost variation happens *within* classes.
# 13 of 15 pairs differ; the exceptions are ambulatory vs emergency and wellness vs inpatient. In plain language:
# inpatient and wellness encounters are typically the most expensive, ambulatory sits in the middle, and outpatient,
# emergency and urgent-care encounters are typically cheapest, although emergency and urgent care have long expensive
# tails. **Practical significance:** a budget that uses one average cost for all encounters would be
# badly wrong; costs need to be planned per class *and* the high-cost tail inside low-median classes (urgent care) needs
# its own monitoring. **Limitation:** this test says nothing about *why* classes differ; H2 and Section 7 address that.
#
# ### H2. Encounters with recorded procedures cost more, within each encounter class
# * **H0:** within a given class, cost distributions are the same for encounters with and without a recorded procedure.
# * **H1:** encounters with ≥1 procedure have stochastically higher cost (one-sided).
# * **Variables:** TOTAL_CLAIM_COST by has_procedure, stratified by class (stratifying stops class differences from
#   masquerading as a procedure effect).
# * **Method:** one-sided Mann–Whitney U in each class, Holm correction across the six tests; effect size = rank-biserial
#   correlation r (= Cliff's δ); ratio of medians for practical size.
# * **Assumptions:** independent observations within and between groups (checked in Section 7); same-shaped
#   distributions are not required for the stochastic-dominance reading used here.

# %%
h2 = []
for c in CLASS_ORDER:
    d = analysis[analysis["class"] == c]
    a, b = d.loc[d.has_procedure, "TOTAL_CLAIM_COST"], d.loc[~d.has_procedure, "TOTAL_CLAIM_COST"]
    u, pv = stats.mannwhitneyu(a, b, alternative="greater")
    r = 2 * u / (len(a) * len(b)) - 1
    h2.append({"class": CLASS_LABEL[c], "n_with": len(a), "n_without": len(b), "median_with": a.median(),
               "median_without": b.median(), "median_ratio": a.median() / b.median(), "U": u, "p_raw": pv,
               "rank_biserial_r": r})
h2 = pd.DataFrame(h2)
h2["p_holm"] = multipletests(h2.p_raw, method="holm")[1]
save_tab(h2.round(4), "T19_H2_procedure_vs_none_by_class")
