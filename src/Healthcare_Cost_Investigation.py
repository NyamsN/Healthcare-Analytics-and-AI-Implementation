# **Interpretation.** In every class, encounters with a recorded procedure cost far more than those without — typically
# several times the median — and the effect sizes are large. Encounters without procedures cost little more than the
# base fee. **Practical significance:** procedure activity is the main cost lever inside every class, so monitoring
# "procedures per encounter" by class is more useful for cost control than tracking encounter counts alone.
# **Limitation:** a procedure is part of the cost by construction (it is a line item), so this confirms the billing
# mechanics rather than revealing a hidden cause; the operational question is *which* procedures and how often.
#
# ### H3. Longer encounters have higher recorded claim costs
# * **H0:** ρ = 0 (no monotonic association between duration and cost) within a class.
# * **H1:** ρ ≠ 0.
# * **Variables:** duration_h and TOTAL_CLAIM_COST. Tested within the four classes where duration varies (wellness and
#   urgent care have a constant 15-minute duration, so no test is possible).
# * **Method:** Spearman rank correlation (monotonic, robust to skew), plus partial Spearman controlling for number of
#   procedures (because long encounters may simply contain more procedures). Holm correction.
# * **Assumptions:** independent pairs (checked in Section 7); monotonic rather than linear relationship. Heavy ties at
#   15 minutes reduce power and are handled by average ranks.

# %%
def partial_spearman(df, x, y, z):
    r = df[[x, y, z]].rank()
    rx = smf.ols(f"{x} ~ {z}", r).fit().resid
    ry = smf.ols(f"{y} ~ {z}", r).fit().resid
    return stats.pearsonr(rx, ry)

h3 = []
